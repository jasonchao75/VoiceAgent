const preferenceKey="voiceagent-td-locale";

export function mountTDLocale(root, {id="td-language", externalControl=false}={}) {
  const control=document.createElement("div");
  control.className="td-language";
  control.innerHTML='<label for="td-language">页面语言 / Language</label><select id="td-language"><option value="zh">中文</option><option value="en">English</option></select>';
  control.querySelector("label").htmlFor=id;
  control.querySelector("select").id=id;
  if (externalControl) {
    root.before(control);
    const visibility = () => { control.hidden = root.hidden; };
    new MutationObserver(visibility).observe(root, {attributes:true, attributeFilter:["hidden"]});
    visibility();
  } else root.prepend(control);
  const select=control.querySelector("select"), sources=new WeakMap(), attributes=new WeakMap();
  let language="zh";
  try { if(localStorage.getItem(preferenceKey)==="en") language="en"; } catch { /* Storage can be unavailable in private contexts. */ }
  select.value=language;
  function translate() {
    const walker=document.createTreeWalker(root,NodeFilter.SHOW_TEXT);
    let node;
    while((node=walker.nextNode())) {
      if(node.parentElement.closest("textarea,pre,script,style,.td-language,.bot-name,#sim-distribution,[data-td-literal]")) continue;
      const raw=node.textContent,previous=sources.get(node);
      const original=previous && raw===previous.rendered ? previous.original : raw;
      const key=original.trim();
      const translated=key==="Connection" && node.parentElement.closest('[data-jev="connection"]') ? "连接配置" : translations[key];
      const next=language==="zh" && translated ? original.replace(key,translated) : original;
      sources.set(node,{original,rendered:next});
      if(raw!==next) node.textContent=next;
    }
    for(const element of root.querySelectorAll("[aria-label],[placeholder]")) {
      const previous=attributes.get(element)||{};
      for(const attribute of ["aria-label","placeholder"]) {
        const raw=element.getAttribute(attribute);
        if(raw===null) continue;
        const source=previous[attribute],original=source && raw===source.rendered ? source.original : raw;
        const next=language==="zh" ? translations[original]||original : original;
        previous[attribute]={original,rendered:next};
        if(raw!==next) element.setAttribute(attribute,next);
      }
      attributes.set(element,previous);
    }
  }
  select.addEventListener("change",()=>{
    language=select.value;
    try { localStorage.setItem(preferenceKey,language); } catch { /* A locale switch must not depend on storage. */ }
    translate();
  });
  new MutationObserver(translate).observe(root,{childList:true,subtree:true,characterData:true});
  translate();
}
